// Rebuilds src/lib/emoji-names-cldr.ts from Unicode's official emoji names (CLDR,
// Unicode License v3, free to use): `npm run emoji:refresh`. Run it after a new
// Unicode release (about once a year, in the autumn), then check the diff and
// commit. It downloads the English and Hindi name files itself, skips every emoji
// that src/lib/emoji-names.ts already names (our playful names win), and skips
// flags, keycaps, arrows, geometric shapes and names with odd characters.
//
// Optional: `node scripts/refresh-emoji-names.mjs <en.xml> <hi.xml>` to use files
// you downloaded yourself instead.

import fs from "node:fs";

const BASE = "https://raw.githubusercontent.com/unicode-org/cldr/main/common/annotations";
const OWN = new URL("../src/lib/emoji-names.ts", import.meta.url);
const OUT = new URL("../src/lib/emoji-names-cldr.ts", import.meta.url);

async function load(lang, localPath) {
  if (localPath) return fs.readFileSync(localPath, "utf8");
  const res = await fetch(`${BASE}/${lang}.xml`);
  if (!res.ok) throw new Error(`Could not download ${lang}.xml: HTTP ${res.status}`);
  return res.text();
}

function parse(xml) {
  const names = new Map();
  for (const m of xml.matchAll(/<annotation cp="([^"]+)" type="tts">([^<]+)<\/annotation>/g)) names.set(m[1], m[2]);
  return names;
}

const [enPath, hiPath] = process.argv.slice(2);
const en = parse(await load("en", enPath));
const hi = parse(await load("hi", hiPath));
if (en.size < 1000 || hi.size < 1000) throw new Error("The name files look too small; not writing anything.");

// Emoji our own file already names (the variation selector is not part of the key).
// Only the playful groups count: the DISTINCT list after them renames some emoji that
// stay in the official table, so it must not hide them from it.
const ownSource = fs.readFileSync(OWN, "utf8");
const own = new Set(
  [...ownSource.slice(0, ownSource.indexOf("// Pairs the official names")).matchAll(/"([^"\s]+)"/g)].map((m) =>
    m[1].replace(/️/g, ""),
  ),
);

// Symbols that are not worth reading: © ® ™, arrows, small geometric shapes and the like.
const SKIP_CP = new Set([0x24c2, 0x2b05, 0x2b06, 0x2b07, 0x2934, 0x2935, 0x3030, 0x303d, 0x3297, 0x3299]);
const skip = (cp) =>
  cp < 0x231a || SKIP_CP.has(cp) || (cp >= 0x25aa && cp <= 0x25fe && cp !== 0x25b6 && cp !== 0x25c0);
const tidy = (s) => s.replace(/[:,'’“”()\-–.]/g, " ").replace(/\s+/g, " ").trim();

const rows = [];
let odd = 0;
for (const [cp, english] of en) {
  if ([...cp].length !== 1) continue;
  if (!/^\p{Extended_Pictographic}$/u.test(cp) || skip(cp.codePointAt(0)) || own.has(cp)) continue;
  const hindi = hi.get(cp);
  if (!hindi) continue;
  const e = tidy(english).toLowerCase();
  const h = tidy(hindi);
  if (!/^[a-z ]+$/.test(e) || !/^[ऀ-ॿ ]+$/.test(h)) {
    odd++;
    continue;
  }
  rows.push(`  ${JSON.stringify(cp)}: [${JSON.stringify(e)}, ${JSON.stringify(h)}],`);
}

// Emoji that share a playful name with an earlier emoji of the same group in emoji-names.ts
// (😂 and 🤣 both "laughing"). Each gets its own official name instead, so two different
// emoji never sound the same. Only the group's first emoji keeps the shared name.
const grouped = [];
for (const m of ownSource.matchAll(/^\s*\[\[([^\]]*)\],/gm)) {
  const members = [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1].replace(/\u{fe0f}/gu, ""));
  for (const cp of members.slice(1)) {
    const english = en.get(cp) ?? en.get(`${cp}\u{fe0f}`);
    const hindi = hi.get(cp) ?? hi.get(`${cp}\u{fe0f}`);
    if (!english || !hindi) continue;
    const e = tidy(english).toLowerCase();
    const h = tidy(hindi);
    if (!/^[a-z ]+$/.test(e) || !/^[ऀ-ॿ ]+$/.test(h)) continue;
    grouped.push(`  ${JSON.stringify(cp)}: [${JSON.stringify(e)}, ${JSON.stringify(h)}],`);
  }
}

fs.writeFileSync(
  OUT,
  `// GENERATED by \`npm run emoji:refresh\` (scripts/refresh-emoji-names.mjs) from Unicode CLDR
// (common/annotations en.xml and hi.xml, Unicode License v3, free to use). Do not edit
// by hand. These are the official names for every emoji that emoji-names.ts does not
// list, so an unlisted emoji is still read aloud. Plain, not playful: add a playful
// line in emoji-names.ts to override. Skipped: flags, keycaps, skin tones and joined
// sequences (they are read by their first symbol), arrows and geometric shapes.

export const CLDR_EMOJI_NAMES: Readonly<Record<string, readonly [string, string]>> = {
${rows.join("\n")}
};

// Official names for the second and later emoji of each shared group in emoji-names.ts,
// so 😂 and 🤣 (or 🎉 and 🎊) are not read as the same word. emoji-names.ts prefers these.
export const CLDR_GROUPED_NAMES: Readonly<Record<string, readonly [string, string]>> = {
${grouped.join("\n")}
};
`,
);
console.log(`Wrote ${rows.length} emoji names and ${grouped.length} grouped-emoji names (skipped ${odd} with odd characters; ${own.size} are ours).`);
